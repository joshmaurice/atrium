function reportKhronos(dir) {
  const entries = readKhronosSubset(dir)
  const problems = manifestHashProblems(dir)
  console.log(`khronos subset: ${entries.length} asset(s); manifest hash problems: ${problems.length}`)
  for (const problem of problems) console.log(`  ${problem.file}: ${problem.problem}`)
  const results = runKhronosSubset(entries)
  const counts = {}
  for (const r of results) counts[r.result] = (counts[r.result] ?? 0) + 1
  console.log(`results: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}`)
  for (const r of results.filter((x) => x.result !== 'pass')) console.log(`  ${r.result.padEnd(9)} ${r.asset} ${r.reason ?? ''}`)
  const changes = baselineChanges(entries, results)
  console.log(`changes against the p6 baseline: ${changes.length}`)
  for (const c of changes) console.log(`  ${c.asset}: ${c.baseline} -> ${c.result}`)
  return { entries, results }
}

