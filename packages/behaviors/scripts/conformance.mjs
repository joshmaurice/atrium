/**
 * Run one asset's graph through the real adapter with the fake world, the
 * injected clock and the injected timers.
 *
 * The outcome is read from the asset's own test channel: `onStart` carries the
 * declared duration, `onSuccess` is a pass and `onFailed` a fail. The clock is
 * simulated (a fixed step per tick, timers fired by due time), so the run is
 * deterministic and does not depend on the build host's speed; the loop stops
 * at the declared duration + 1 s (capped), at the tick cap, or when the
 * adapter disposes the engine.
 *
 * @returns {{asset: string, result: string, reason?: string}}
 */
export function runKhronosAsset(entry, { stepMs = 16, capMs = 15000, maxTicks = 4000 } = {}) {
  const nodes = entry.nodes ?? []
  const world = fakeConformanceWorld(nodes)
  const timers = new Map()
  let seq = 0
  let nowMs = 0
  const injectedSetTimeout = (fn, ms) => { const id = ++seq; timers.set(id, { fn, due: nowMs + ms, seq: id }); return id }
  const injectedClearTimeout = (id) => { timers.delete(id) }

  const engine = createBehaviorEngine({
    graph: entry.graph,
    nodeMap: nodes.map((_n, i) => String(i)),
    animations: [],
    world,
    now: () => nowMs,
    setTimeout: injectedSetTimeout,
    clearTimeout: injectedClearTimeout,
    log: () => {},
  })
  if (engine.problem) return { asset: entry.asset, result: 'rejected', reason: String(engine.message ?? 'rejected') }

  let outcome = null
  let durationMs = 5000
  const bus = engine.eventBus
  const original = bus.dispatchCustomEvent
  bus.dispatchCustomEvent = (name, vals) => {
    const channel = String(name).replace(/^KHR_INTERACTIVITY:/, '')
    if (channel === 'test/onStart') durationMs = Number(vals?.expectedDuration?.[0] ?? vals?.expectedDuration ?? 5) * 1000
    if (channel === 'test/onSuccess') outcome ??= 'pass'
    if (channel === 'test/onFailed') outcome ??= 'fail'
    return original(name, vals)
  }

  const limitMs = Math.min(durationMs + 1000, capMs)
  let ticks = 0
  let verdict
  try {
    while (outcome === null && !engine.disposed && nowMs < limitMs && ticks < maxTicks) {
      nowMs += stepMs
      ticks += 1
      for (const timer of [...timers.values()].filter((t) => t.due <= nowMs).sort((a, b) => a.due - b.due || a.seq - b.seq)) {
        timers.delete(timer.seq)
        timer.fn()
      }
      engine.tick()
    }
    // Read the disposition BEFORE the finally disposes: `disposed` is true for
    // both, and only the loop's own disposal has a reason.
    if (outcome !== null) verdict = { result: outcome }
    else if (engine.disposed) verdict = { result: 'disposed', reason: engine.reason ?? undefined }
    else verdict = { result: 'no result', reason: `after ${ticks} ticks` }
  } catch (error) {
    return { asset: entry.asset, result: 'threw', reason: String(error?.message ?? error) }
  } finally {
    try { engine.dispose() } catch { /* total */ }
  }
  return { asset: entry.asset, ...verdict }
}

/** The whole checked-in subset, in manifest order. */
export function runKhronosSubset(entries, options = {}) {
  return entries.map((entry) => runKhronosAsset(entry, options))
}

/** The regenerated expected list, or null when it is not checked in yet. */
export function readExpected4d(file = EXPECTED_4D_FILE) {
  try { return JSON.parse(readFileSync(file, 'utf8')) } catch { return null }
}

/** The mechanical delta of a regenerated list against the manifest's baseline. */
export function baselineChanges(entries, results) {
  const byAsset = new Map(results.map((r) => [r.asset, r]))
  return entries
    .map((entry) => ({ asset: entry.asset, baseline: entry.baseline, result: byAsset.get(entry.asset)?.result }))
    .filter((row) => row.result !== undefined && row.result !== row.baseline)
}

