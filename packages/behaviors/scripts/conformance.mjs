/** The manifest itself, exactly as checked in. */
export function khronosManifest(dir = KHRONOS_SUBSET_DIR) {
  return JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'))
}

/**
 * G8 — the checked-in subset: one entry per manifest line, with the graph and
 * the asset's nodes read from the checked-in file. The sha256 is computed from
 * the bytes on disk, so a caller can check it against the manifest's.
 */
export function readKhronosSubset(dir = KHRONOS_SUBSET_DIR) {
  return (khronosManifest(dir).entries ?? []).map((entry) => {
    const bytes = readFileSync(join(dir, entry.file))
    const parsed = JSON.parse(bytes.toString('utf8'))
    return {
      asset: entry.asset,
      file: entry.file,
      sha256: sha256Hex(bytes),
      manifestSha256: entry.sha256,
      baseline: entry.baseline,
      graph: parsed.graph,
      nodes: parsed.nodes ?? [],
    }
  })
}

/**
 * G8's test row: "the manifest's hashes match the files". Returns one problem
 * per mismatch (an empty array is the pass), plus a problem for a file the
 * manifest lists but that has no graph.
 *
 * @returns {Array<{file: string, problem: string, expected?: string, got?: string}>}
 */
export function manifestHashProblems(dir = KHRONOS_SUBSET_DIR) {
  const manifest = khronosManifest(dir)
  const problems = []
  for (const entry of manifest.entries ?? []) {
    let bytes
    try { bytes = readFileSync(join(dir, entry.file)) } catch (error) {
      problems.push({ file: entry.file, problem: `the file is missing: ${error?.message ?? error}` })
      continue
    }
    const got = sha256Hex(bytes)
    if (got !== entry.sha256) problems.push({ file: entry.file, problem: 'sha256 differs', expected: entry.sha256, got })
    try {
      const parsed = JSON.parse(bytes.toString('utf8'))
      if (!parsed || !Array.isArray(parsed.graph?.declarations)) {
        problems.push({ file: entry.file, problem: 'the file carries no graph declarations' })
      }
    } catch (error) {
      problems.push({ file: entry.file, problem: `not JSON: ${error?.message ?? error}` })
    }
  }
  if (typeof manifest.count === 'number' && manifest.count !== (manifest.entries ?? []).length) {
    problems.push({ file: 'manifest.json', problem: `count is ${manifest.count}, entries are ${(manifest.entries ?? []).length}` })
  }
  return problems
}

