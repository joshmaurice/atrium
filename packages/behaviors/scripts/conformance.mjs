/** Every 4d fixture, in file order, as `{ file, fixture }`. */
export function read4dFixtures(dir = CONFORMANCE_4D_DIR) {
  return readdirSync(dir).filter((name) => name.endsWith('.json')).sort()
    .map((file) => ({ file, fixture: JSON.parse(readFileSync(join(dir, file), 'utf8')) }))
}

/** README rule 6 — a non-finite number is compared as its own string. */
function encode4d(value) {
  if (Array.isArray(value)) return value.map(encode4d)
  if (typeof value === 'number' && !Number.isFinite(value)) return String(value)
  return value
}

/**
 * README "The harness rules" — one fixture through the REAL adapter, with the
 * fake world, the injected clock and the injected timers (G3):
 *
 *  1. the world holds one value per `(index, field)`, seeded from `world.initial`,
 *     and every `nodeMap` index is the own node or a descendant (authority never
 *     refuses);
 *  2. a read sees the host's own accepted writes (G-L6's overlay);
 *  3. every write passes G4's value check (`src/value-rules.js`, the server's own
 *     rules): an accepted write is applied and recorded in `writes`, a refused
 *     one is recorded in `refused` and changes nothing;
 *  4. for step `k` (1 … ticks), `now = startMs + (k − 1) × stepMs`; before tick
 *     `k`, every timer due at or before `now` fires (by due time, ties in
 *     scheduling order), then the fixture's events, then one tick;
 *  5. a delay of `d` seconds scheduled at `t` is due at `t + 1000 × d` ms;
 *  6. a write is recorded with the `k` of the tick it happened in.
 *
 * Step 7 (the run stops at `ticks`, or when the adapter disposes the engine) is
 * the loop itself.
 *
 * @returns {{id: string, writes: Array, refused: Array, disposed: *, unsupported: Array, error?: string}}
 */
export function run4dFixture(fixture) {
  const n = fixture.nodeMap.length
  const clock = fixture.clock ?? { startMs: 0, stepMs: 100 }
  const lights = new Set(fixture.world?.lights ?? [])
  const state = new Map()
  for (const [index, fields] of Object.entries(fixture.world?.initial ?? {})) {
    for (const [field, value] of Object.entries(fields)) state.set(`${index}:${field}`, value)
  }

  const writes = []
  const refused = []
  let tick = 0

  const world = {
    resolve: (i) => (Number(i) >= 0 && Number(i) < n ? { objectId: fixture.nodeMap[Number(i)], name: `node-${i}` } : { problem: 'not-found' }),
    isOwnOrDescendant: (i) => Number(i) >= 0 && Number(i) < n,
    isGranted: () => false,
    hasLight: (i) => lights.has(i),
    get: (i, field) => state.get(`${i}:${field}`),
    set: (i, field, value) => {
      if (nodeValueProblem(field, value) !== null) { refused.push({ tick, index: i, field, value: encode4d(value) }); return false }
      state.set(`${i}:${field}`, value)
      writes.push({ tick, index: i, field, value: encode4d(value) })
      return true
    },
    lightIntensity: (i) => state.get(`${i}:intensity`),
    setLightIntensity: (i, value) => {
      if (lightValueProblem('intensity', value) !== null) { refused.push({ tick, index: i, field: 'intensity', value: encode4d(value) }); return false }
      state.set(`${i}:intensity`, value)
      writes.push({ tick, index: i, field: 'intensity', value: encode4d(value) })
      return true
    },
    lightColor: (i) => state.get(`${i}:color`),
    setLightColor: (i, value) => {
      if (lightValueProblem('color', value) !== null) { refused.push({ tick, index: i, field: 'color', value: encode4d(value) }); return false }
      state.set(`${i}:color`, value)
      writes.push({ tick, index: i, field: 'color', value: encode4d(value) })
      return true
    },
    matrix: () => IDENTITY4,
    worldMatrix: () => IDENTITY4,
    clipStatus: () => ({ status: 'none' }),
    play: () => true,
    stop: () => true,
    worldPosition: () => [0, 0, 0],
    parentIndex: () => null,
  }

  const timers = new Map()
  let seq = 0
  let nowMs = clock.startMs
  const injectedSetTimeout = (fn, ms) => { const id = ++seq; timers.set(id, { fn, due: nowMs + ms, seq: id }); return id }
  const injectedClearTimeout = (id) => { timers.delete(id) }

  // G3's identity gate, the clock and the timers are the ADAPTER's own: the
  // stored graph is validated and a renamed copy is loaded, so nothing here
  // emulates 4d.
  const engine = createBehaviorEngine({
    graph: fixture.graph,
    nodeMap: [...fixture.nodeMap],
    animations: [],
    world,
    now: () => nowMs,
    setTimeout: injectedSetTimeout,
    clearTimeout: injectedClearTimeout,
    log: () => {},
  })
  if (engine.problem) return { id: fixture.id, error: `rejected: ${engine.message}` }

  let verdict
  try {
    for (let k = 1; k <= fixture.ticks; k++) {
      tick = k
      nowMs = clock.startMs + (k - 1) * clock.stepMs
      for (const timer of [...timers.values()].filter((t) => t.due <= nowMs).sort((a, b) => a.due - b.due || a.seq - b.seq)) {
        timers.delete(timer.seq)
        timer.fn()
      }
      for (const event of fixture.events ?? []) {
        if (event.beforeTick === k && event.select !== undefined) engine.select(event.select)
      }
      if (engine.disposed) break
      engine.tick()
    }
    // Read the disposition BEFORE the finally disposes (README rule 7: the run
    // stops when the ticks are done, or when the engine is disposed).
    verdict = {
      id: fixture.id,
      writes,
      refused,
      disposed: engine.disposed ? (engine.reason ?? true) : false,
      // G-L3 (a) — the report the form and the importer share, in the fixture's
      // `{ op, extension }` shape.
      unsupported: graphReport({ graph: fixture.graph }).unsupported.map(({ op, extension }) => ({ op, extension })),
    }
  } finally {
    try { engine.dispose() } catch { /* total */ }
  }
  return verdict
}

/** `same` — the README's comparison: numbers within `tolerance`, else deep equal. */
export function same4d(a, b, tolerance = 1e-9) {
  if (typeof a === 'number' && typeof b === 'number') return Math.abs(a - b) <= tolerance
  if (Array.isArray(a) || Array.isArray(b)) {
    return Array.isArray(a) && Array.isArray(b) && a.length === b.length && a.every((x, i) => same4d(x, b[i], tolerance))
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    const keys = Object.keys(a)
    return keys.length === Object.keys(b).length && keys.every((k) => same4d(a[k], b[k], tolerance))
  }
  return a === b
}

/**
 * G8's first test row: "every fixture's write log matches exactly". One verdict
 * per fixture, with the wanted and the got value for a fixture that differs.
 *
 * @returns {Array<{id: string, file: string, ok: boolean, reason?: string,
 *                  want?: object, got?: object, requires4d?: string[]}>}
 */
export function check4dFixtures(dir = CONFORMANCE_4D_DIR) {
  return read4dFixtures(dir).map(({ file, fixture }) => {
    let got
    try {
      got = run4dFixture(fixture)
    } catch (error) {
      return { id: fixture.id, file, ok: false, reason: `threw: ${error?.message ?? error}`, requires4d: fixture.requires4d ?? [] }
    }
    const tolerance = fixture.tolerance ?? 1e-9
    const want = { writes: fixture.expect.writes, refused: fixture.expect.refused, disposed: fixture.expect.disposed }
    if (got.error) return { id: fixture.id, file, ok: false, reason: got.error, want, requires4d: fixture.requires4d ?? [] }
    const have = { writes: got.writes, refused: got.refused, disposed: got.disposed }
    let ok = same4d(have, want, tolerance)
    if (ok && fixture.expect.unsupported) ok = same4d(got.unsupported, fixture.expect.unsupported, 0)
    return {
      id: fixture.id,
      file,
      ok,
      reason: ok ? undefined : 'the write log (or the refusal log, the disposition, or the unsupported list) differs',
      want,
      got: fixture.expect.unsupported && !same4d(got.unsupported, fixture.expect.unsupported, 0)
        ? { ...have, unsupported: got.unsupported }
        : have,
      requires4d: fixture.requires4d ?? [],
    }
  })
}

